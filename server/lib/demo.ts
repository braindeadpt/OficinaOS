import { AppError } from "@shared/errors/app-error.js";
import { loadEnv } from "../config/env.js";

/**
 * DEMO_MODE — public demo at demo.oficinaos.app.
 *
 * A visitor clicks «Experimentar a demo» and lands in a fictional repair
 * shop that is reset hourly. Everything that could reach the outside world
 * (email, WhatsApp/SMS, webhooks, the AI assistant, Cloud/Trade pairing,
 * exports, integrations) is switched off server-side — never only hidden
 * in the UI — and sensitive management routes return 403.
 */

export const DEMO_USERNAME = "demo";
// Fixed credential the demo login endpoint uses to open a real session.
// Public by design (it is in the repo): it only ever unlocks the fictional
// demo user, which anyone can already reach via POST /api/demo/login.
export const DEMO_PASSWORD = "demo-mode-oficinaos-2026";

export function isDemoMode(): boolean {
  return loadEnv().DEMO_MODE;
}

/** Throws 403 DEMO_DISABLED when the server runs in DEMO_MODE. */
export function assertNotDemoMode(): void {
  if (isDemoMode()) {
    throw new AppError("DEMO_DISABLED");
  }
}

// ── Route blocklist ────────────────────────────────────────────────────
// Two buckets: routes blocked for every method (the whole feature talks to
// the outside) and routes blocked only for mutations (GETs keep feeding the
// settings UI so pages render instead of erroring).

const BLOCKED_ALL_METHODS = [
  // AI assistant — the whole surface exists to call a model API.
  "/api/ai",
  // Proxies/boards that live on oficinaos-cloud or the Trade marketplace.
  "/api/part-requests",
  "/api/market-prices",
  "/api/storefront",
  // Bulk exports exfiltrate the dataset in one click.
  "/api/export",
  // Cloud pairing, sync and unpair.
  "/api/settings/cloud",
  // Self-update reaches github.com and spawns a PowerShell that swaps the
  // install — unacceptable on a shared public demo.
  "/api/settings/update",
  // Evolution (WhatsApp LAN bridge) status/pair/disconnect all hit the
  // gateway — nothing to pair on a hosted demo anyway.
  "/api/settings/whatsapp/evolution",
] as const;

const BLOCKED_MUTATIONS = [
  // First-run setup would create a real owner on the shared demo.
  "/api/setup",
  // User/role management (create, edit, status, reset-password, sessions,
  // avatar): the demo user is the only account and must stay as seeded.
  "/api/users",
  // Integration settings: WhatsApp credentials, SMS gateway, AI endpoint,
  // InvoiceXpress account — all carry secrets or trigger outside calls.
  "/api/settings/whatsapp",
  "/api/settings/sms",
  "/api/settings/ai",
  "/api/settings/invoicing",
  // Opens a raw TCP socket to a LAN printer.
  "/api/settings/printer-test",
  // Sends a real WhatsApp/SMS through the configured channel.
  "/api/notifications/test",
  // Every report opens a public GitHub issue.
  "/api/feedback",
] as const;

// Better-auth exposes its whole surface under /api/auth/* — including the
// admin plugin (user mgmt, ban, impersonate), password/email changes and
// password-reset email sends. In demo the only allowed auth mutation is
// sign-out: credential sign-ins go through /api/demo/login so scripted
// failures can't lock the shared demo account out for everyone.
const ALLOWED_AUTH_MUTATIONS = new Set(["/api/auth/sign-out"]);

const isMutationMethod = (method: string) =>
  method === "POST" ||
  method === "PUT" ||
  method === "PATCH" ||
  method === "DELETE";

const startsWithAny = (path: string, prefixes: readonly string[]) =>
  prefixes.some((p) => path === p || path.startsWith(`${p}/`));

/**
 * Whether DEMO_MODE refuses this request. Checked in a global onRequest
 * hook — bypassing a disabled UI button still hits this.
 */
export function isDemoBlocked(method: string, pathname: string): boolean {
  if (pathname.startsWith("/api/auth/")) {
    return isMutationMethod(method) && !ALLOWED_AUTH_MUTATIONS.has(pathname);
  }
  if (startsWithAny(pathname, BLOCKED_ALL_METHODS)) {
    return true;
  }
  return isMutationMethod(method) && startsWithAny(pathname, BLOCKED_MUTATIONS);
}

// Fiscal documents go to InvoiceXpress (a real external provider).
const INVOICE_ROUTE = /^\/api\/(jobs|sales)\/[^/]+\/invoice$/;
// The diagnostic AI report is generated by the Cloud `ai-reports` module.
const INTAKE_AI_REPORT = /^\/api\/intake-requests\/[^/]+\/ai-report$/;

export function isDemoBlockedPath(method: string, pathname: string): boolean {
  if (isDemoBlocked(method, pathname)) {
    return true;
  }
  return (
    isMutationMethod(method) &&
    (INVOICE_ROUTE.test(pathname) || INTAKE_AI_REPORT.test(pathname))
  );
}

/** Largest import the demo accepts — bulk imports stay blocked above this. */
export const DEMO_IMPORT_MAX_ROWS = 50;

/**
 * Path the demo guard evaluates. For concrete routes the matched
 * routeOptions.url pattern is already normalized by the router (%XX is
 * decoded before matching, so /api/%75sers/... lands on /api/users/:id).
 * For wildcard handlers (the better-auth /api/auth/* catch-all) and
 * unmatched paths we decode the raw URL ourselves — otherwise an encoded
 * path would sail past the prefix blocklist while still hitting a handler.
 */
export function demoRequestPath(
  routePattern: string | undefined,
  rawUrl: string
): string {
  if (routePattern && routePattern !== "/" && !routePattern.includes("*")) {
    return routePattern;
  }
  const raw = rawUrl.split("?", 1)[0];
  let decoded: string;
  try {
    decoded = decodeURIComponent(raw);
  } catch {
    throw new AppError("VALIDATION_ERROR");
  }
  return decoded.replace(/\/{2,}/g, "/").toLowerCase();
}

// The database name must be exactly "demo" or carry it as a delimited
// segment (oficinaos_demo, demo_it_123): a substring match would let
// "demolition" or "notademo" through, which is precisely the accident
// this guard exists to prevent.
const DEMO_DB_NAME = /(^|_)demo(_|$)/i;

/**
 * Second safety net for the destructive demo paths (seed, hourly reset):
 * the target database's name must be "demo" (or contain it as a
 * _-delimited segment), so a mispointed DATABASE_URL can never wipe a
 * real shop.
 */
export function assertDemoDatabase(databaseUrl: string): void {
  let dbName = "";
  try {
    const raw = new URL(databaseUrl).pathname.split("/").pop() ?? "";
    // DB names may be percent-encoded in the URL — compare the real name.
    dbName = decodeURIComponent(raw);
  } catch {
    // unparsable — falls through to the throw below
  }
  if (!DEMO_DB_NAME.test(dbName)) {
    throw new Error(
      `Refusing demo wipe on database "${dbName || "unknown"}" — name must be or contain "_demo_".`
    );
  }
}

// RFC1918/CGNAT/link-local/loopback — a peer in one of these ranges is
// inside our own deployment (the cloudflared connector or the edge
// proxy), so its CF-Connecting-IP header is infrastructure-set, not
// client-controlled. Anyone else hitting the origin directly keeps the
// socket IP as their key — a forged header then buys them nothing.
const PRIVATE_IP =
  /^(10\.|192\.168\.|172\.(1[6-9]|2\d|3[01])\.|100\.(6[4-9]|[7-9]\d|1[01]\d|12[0-7])\.|127\.|169\.254\.|::1$|fd|fe80)/i;

/**
 * DEMO_MODE rate-limit key: behind cloudflared/Caddy every request arrives
 * from the proxy IP, so the whole visitor pool would share one budget
 * (and ban:5 would let a single script block everyone). CF-Connecting-IP
 * is what cloudflared forwards to the origin — but it is just an HTTP
 * header, so we only honor it when the peer is trusted: either it came
 * from a private/internal IP (i.e. our own proxy infrastructure), or the
 * operator explicitly set DEMO_TRUST_CF_CONNECTING_IP=true. A direct hit
 * on a public socket falls back to request.ip, where rotating the header
 * cannot mint extra budgets. Only used in demo mode — real installs keep
 * request.ip and the explicit TRUST_PROXY opt-in.
 */
export function demoRateLimitKey(request: {
  headers: Record<string, unknown>;
  ip: string;
}): string {
  const cfIp = request.headers["cf-connecting-ip"];
  const trusted =
    loadEnv().DEMO_TRUST_CF_CONNECTING_IP || PRIVATE_IP.test(request.ip);
  return trusted && typeof cfIp === "string" && cfIp.length > 0
    ? cfIp
    : request.ip;
}
