import { normalizeDocumentLocale } from "../../lib/document-locale.js";

export type RegistosLang = "en" | "es" | "fr" | "pt";

/** Língua documental normalizada — aceita um locale solto («pt-PT») ou
 *  undefined (loja PT histórica) e devolve sempre uma das quatro. */
export function registosLang(locale: string | null | undefined): RegistosLang {
  return normalizeDocumentLocale(locale) as RegistosLang;
}

/** Tag BCP 47 para o Intl — en-GB e não en-US: dia-mês como na Europa,
 *  coerente com o que o trabalhador vê no resto da app. */
const INTL_LOCALE: Record<RegistosLang, string> = {
  en: "en-GB",
  es: "es-ES",
  fr: "fr-FR",
  pt: "pt-PT",
};

export function registosIntlLocale(lang: RegistosLang): string {
  return INTL_LOCALE[lang];
}

/** «outubro de 2026» / «October 2026» — o Intl trata da preposição e da
 *  ordem em cada língua; substitui os arrays de nomes de meses hardcoded. */
export function registosMonthLabel(
  spec: { month: number; year: number },
  lang: RegistosLang
): string {
  return new Intl.DateTimeFormat(INTL_LOCALE[lang], {
    month: "long",
    timeZone: "UTC",
    year: "numeric",
  }).format(new Date(Date.UTC(spec.year, spec.month - 1, 1)));
}

