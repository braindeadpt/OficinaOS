/** Substituição simples de placeholders {{chave}} — sem escaping, os
 *  valores são números, horas formatadas ou etiquetas de mês. */
export function registosT(
  template: string,
  vars: Record<string, string>
): string {
  let out = template;
  for (const [key, value] of Object.entries(vars)) {
    out = out.replaceAll(`{{${key}}}`, value);
  }
  return out;
}
